class ZiyaratPage extends StatelessWidget {
  const ZiyaratPage({super.key});

  @override
  Widget build(BuildContext context) {
    return IslamicPatternBackground(
      child: Scaffold( backgroundColor: Colors.transparent,
      appBar: AppBar(title: const Text('الزيارات والمناسبات')),
      body: ListView.builder(
        padding: const EdgeInsets.fromLTRB(12, 12, 12, 100),
        itemCount: _ziyarat.length,
        itemBuilder: (ctx, i) {
          final z = _ziyarat[i];
          return Card(
            margin: const EdgeInsets.only(bottom: 12),
            shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(14)),
            child: ListTile(
              contentPadding: const EdgeInsets.all(16),
              leading: CircleAvatar(
                backgroundColor: z.color.withOpacity(0.12),
                radius: 28,
                child: Icon(z.icon, color: z.color, size: 28),
              ),
              title: Text(
                z.title,
                style: TextStyle(
                  fontSize: 18,
                  fontWeight: FontWeight.bold,
                  color: z.color,
                ),
              ),
              subtitle: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const SizedBox(height: 4),
                  Text(z.subtitle, style: const TextStyle(fontSize: 13)),
                  const SizedBox(height: 2),
                  Row(
                    children: [
                      Icon(Icons.calendar_today,
                          size: 12,
                          color: Theme.of(context)
                              .colorScheme
                              .onSurface
                              .withOpacity(0.5)),
                      const SizedBox(width: 4),
                      Text(
                        z.occasion,
                        style: TextStyle(
                          fontSize: 11,
                          color: Theme.of(context)
                              .colorScheme
                              .onSurface
                              .withOpacity(0.5),
                        ),
                      ),
                    ],
                  ),
                ],
              ),
              trailing: Icon(Icons.chevron_left,
                  color: z.color),
              onTap: () => Navigator.push(
                ctx,
                MaterialPageRoute(
                    builder: (_) => _ZiyaraReaderPage(ziyara: z)),
              ),
            ),
          );
        },
      ),
    ),
    );
  }
}

